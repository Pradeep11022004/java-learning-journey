
public class AddTwoNumbers {

    static void add(int firstNumber, int secondNumber) {
        System.out.println("Sum = " + (firstNumber + secondNumber));
    }

    public static void main(String[] args) {

        add(10, 20);
        add(50, 25);
        add(100, 200);
        add(-10, 40);

    }
}
