public class OddNumbers{
    public static void main(String[] args) {
        
         System.out.println("===== Print Odd Numbers (1 to 20) =====");
        
        for(int i=1;i<=20;i++){
         if(i%2!=0){
            System.out.println(i);
         }
        }
        System.out.println("===================================");
    }
}
